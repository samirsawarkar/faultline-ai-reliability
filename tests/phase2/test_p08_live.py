def test_responses_jsonl_has_both_steps(tmp_path: Path):
    manifest = ensure_manifest(tmp_path)
    sample_ids = manifest["sample_ids"][:3]
    trace_store = TraceStore(str(tmp_path / "trace.db"))
    ledger = CostLedger(ledger_path=tmp_path / "ledger.jsonl")
    price_table = PriceTable(
        rungs={
            "R1": RungPricing(model_name="mock", input_price_per_m=0.0, output_price_per_m=0.0),
            "R2": RungPricing(model_name="mock", input_price_per_m=0.0, output_price_per_m=0.0),
        }
    )

    def ungrounded_content(messages):
        from faultline_p2.policy.provenance import parse_tool_block
        sys_prompt = messages[0]["content"]
        tools = parse_tool_block(sys_prompt)
        for t, args in tools.items():
            if args:
                call = {"tool": t, "arguments": {args[0]: "totally_ungrounded_secret_value_xyz123"}}
                return json.dumps(call)
        return '{"tool": "unknown", "arguments": {}}'

    stub_subject = StubRawTextModel(content=ungrounded_content)
    stub_judge = StubRawTextModel(content="GRADE: Invalid")

    log_dir = tmp_path / "logs" / "arm_b" / "R1"
    run_arm_b(
        rung="R1",
        model_string="mock",
        sample_ids=sample_ids,
        judge_model="z-ai/glm-5.3-flash",
        trace_store=trace_store,
        ledger=ledger,
        price_table=price_table,
        log_dir=log_dir,
        smoke=True,
        models=(stub_subject, stub_judge),
    )

    responses_file = log_dir / "responses.jsonl"
    assert responses_file.exists()
    lines = [json.loads(l) for l in responses_file.read_text().splitlines() if l.strip()]
    assert len(lines) == len(sample_ids) * 2

    by_sample = {}
    for entry in lines:
        sid = entry["sample_id"]
        by_sample.setdefault(sid, []).append(entry["step"])

    for sid in sample_ids:
        assert sorted(by_sample[sid]) == [1, 2]


