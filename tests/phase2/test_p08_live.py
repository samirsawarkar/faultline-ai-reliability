def test_reuse_arm_a_skips_worker(tmp_path: Path, monkeypatch):
    """Verify run_arm_a with reuse=True parses existing .eval log without invoking worker."""
    # Step 1: Run smoke into tmp_path to generate a valid smoke .eval log
    smoke_dir = tmp_path / "smoke_run"
    ret = run_smoke(output_dir=smoke_dir, rungs=["R1"])
    assert ret == 0

    smoke_log_dir = smoke_dir / "logs" / "arm_a" / "R1"
    eval_files = list(smoke_log_dir.glob("*.eval"))
    assert len(eval_files) > 0, "No .eval log generated by smoke run"

    # Step 2: Target log_dir with a copy of the smoke .eval log
    target_log_dir = tmp_path / "target_logs"
    target_log_dir.mkdir(parents=True, exist_ok=True)
    for ef in eval_files:
        shutil.copy(ef, target_log_dir / ef.name)

    # Step 3: Monkeypatch subprocess.run to raise AssertionError if invoked
    def mock_subprocess_run(*args, **kwargs):
        raise AssertionError("subprocess.run was unexpectedly called when reuse=True!")

    monkeypatch.setattr(subprocess, "run", mock_subprocess_run)

    trace_store = TraceStore(str(tmp_path / "trace_reuse.db"))
    ledger = CostLedger(ledger_path=tmp_path / "ledger_reuse.jsonl")
    price_table = PriceTable(
        rungs={
            "R1": RungPricing(model_name="mock", input_price_per_m=0.0, output_price_per_m=0.0),
            "R2": RungPricing(model_name="mock", input_price_per_m=0.0, output_price_per_m=0.0),
        }
    )
    manifest = ensure_manifest(tmp_path)
    sample_ids = manifest["sample_ids"][:3]

    res = run_arm_a(
        rung="R1",
        model_string="mock",
        sample_ids=sample_ids,
        judge_model="z-ai/glm-5.3-flash",
        log_dir=target_log_dir,
        trace_store=trace_store,
        ledger=ledger,
        price_table=price_table,
        smoke=False,
        reuse=True,
    )

    assert res["n"] == 3
    assert "asr_over_all" in res
    assert "asr_over_valid" in res


