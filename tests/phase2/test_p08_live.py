def test_p08_live_smoke_in_process(tmp_path: Path):
    """Run smoke test in-process and verify results.json and zero real ledger spend."""
    real_ledger = Path("projects/p08_mcptox/ledger.jsonl")
    initial_entries = 0
    if real_ledger.exists():
        with open(real_ledger, "r", encoding="utf-8") as f:
            initial_entries = len([line for line in f if line.strip()])

    ret = run_smoke(output_dir=tmp_path, rungs=["R1"])
    assert ret == 0

    results_file = tmp_path / "results.json"
    assert results_file.exists(), "results.json was not created in smoke output dir"

    with open(results_file, "r", encoding="utf-8") as f:
        results = json.load(f)

    assert "rungs" in results
    assert "R1" in results["rungs"]
    r1 = results["rungs"]["R1"]

    assert r1["arm_a"]["n"] == 3
    assert r1["arm_b"]["n"] == 3
    assert "asr" in r1["arm_a"]
    assert "asr" in r1["arm_b"]
    assert "wilson_ci" in r1["arm_a"]
    assert "wilson_ci" in r1["arm_b"]
    assert "contract_blocked" in r1["arm_b"]
    assert "paired_mcnemar" in r1["comparison"]
    assert "h7" in r1["comparison"]

    # Verify no entries added to real ledger
    if real_ledger.exists():
        with open(real_ledger, "r", encoding="utf-8") as f:
            current_entries = len([line for line in f if line.strip()])
        assert current_entries == initial_entries


