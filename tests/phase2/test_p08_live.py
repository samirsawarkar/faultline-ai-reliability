def test_arm_b_retry_mode_semantics(tmp_path: Path):
    """Verify retry_mode='call-only' suppresses retries on prose, while 'any' retries all."""
    manifest = ensure_manifest(tmp_path)
    sample_ids = manifest["sample_ids"][:3]
    trace_store = TraceStore(str(tmp_path / "trace.db"))
    ledger = CostLedger(ledger_path=tmp_path / "ledger.jsonl")
    price_table = PriceTable(
        rungs={
            "R1": RungPricing(model_name="mock", input_price_per_m=0.0, output_price_per_m=0.0),
            "R2": RungPricing(model_name="mock", input_price_per_m=0.0, output_price_per_m=0.0),
        }
    )

    stub_subject = StubRawTextModel(content="I cannot help with that.")
    stub_judge = StubRawTextModel(content="GRADE: Failure-Refused")

    # 1. Call-only mode: prose does not trigger retry (1 row per sample)
    log_dir_call_only = tmp_path / "logs" / "arm_b_call_only"
    res_call_only = run_arm_b(
        rung="R1",
        model_string="mock",
        sample_ids=sample_ids,
        judge_model="z-ai/glm-5.3-flash",
        trace_store=trace_store,
        ledger=ledger,
        price_table=price_table,
        log_dir=log_dir_call_only,
        smoke=True,
        models=(stub_subject, stub_judge),
        retry_mode="call-only",
    )
    assert res_call_only["n_by_category"] == {"Failure-Refused": 3}
    responses_file_co = log_dir_call_only / "responses.jsonl"
    assert responses_file_co.exists()
    lines_co = [json.loads(l) for l in responses_file_co.read_text().splitlines() if l.strip()]
    assert len(lines_co) == len(sample_ids)  # 1 row per sample

    # 2. Any mode: legacy behavior retries all non-allowed (2 rows per sample)
    log_dir_any = tmp_path / "logs" / "arm_b_any"
    res_any = run_arm_b(
        rung="R1",
        model_string="mock",
        sample_ids=sample_ids,
        judge_model="z-ai/glm-5.3-flash",
        trace_store=trace_store,
        ledger=ledger,
        price_table=price_table,
        log_dir=log_dir_any,
        smoke=True,
        models=(stub_subject, stub_judge),
        retry_mode="any",
    )
    assert res_any["n_by_category"] == {"Failure-Refused": 3}
    responses_file_any = log_dir_any / "responses.jsonl"
    assert responses_file_any.exists()
    lines_any = [json.loads(l) for l in responses_file_any.read_text().splitlines() if l.strip()]
    assert len(lines_any) == len(sample_ids) * 2  # 2 rows per sample


def test_arm_b_sample_exception_handling(tmp_path: Path):
    """Verify sample exceptions are caught in Arm B, recorded as Error, and run completes normally."""
    manifest = ensure_manifest(tmp_path)
    sample_ids = manifest["sample_ids"][:3]
    trace_store = TraceStore(str(tmp_path / "trace.db"))
    ledger = CostLedger(ledger_path=tmp_path / "ledger.jsonl")
    price_table = PriceTable(
        rungs={
            "R1": RungPricing(model_name="mock", input_price_per_m=0.0, output_price_per_m=0.0),
            "R2": RungPricing(model_name="mock", input_price_per_m=0.0, output_price_per_m=0.0),
        }
    )

    call_count = 0

    def generate_fn(messages):
        nonlocal call_count
        call_count += 1
        if call_count == 2:
            raise RuntimeError("Connection error during live inference")
        return "GRADE: Failure-Refused" if "Judge" in messages[0]["content"] else "I refuse this task."

    stub_subject = StubRawTextModel(content=generate_fn)
    stub_judge = StubRawTextModel(content="GRADE: Failure-Refused")

    log_dir = tmp_path / "logs" / "arm_b" / "R1"
    res = run_arm_b(
        rung="R1",
        model_string="mock",
        sample_ids=sample_ids,
        judge_model="z-ai/glm-5.3-flash",
        trace_store=trace_store,
        ledger=ledger,
        price_table=price_table,
        log_dir=log_dir,
        smoke=True,
        models=(stub_subject, stub_judge),
    )

    assert res["n"] == 3
    assert res["errors"] == 1
    assert res["n_by_category"].get("Error") == 1
    assert res["n_valid"] == 2
    responses_file = log_dir / "responses.jsonl"
    assert responses_file.exists()
    lines = [json.loads(l) for l in responses_file.read_text().splitlines() if l.strip()]
    error_entries = [entry for entry in lines if entry.get("category") == "Error"]
    assert len(error_entries) == 1
    assert "Connection error" in error_entries[0].get("error", "")


